"""Build the Hugging Face Space repository content from the GitHub-intended files.

The output is the GitHub code plus two generated files that exist only in the Space:
- `README.md` with the Spaces front matter from `space.yaml` prepended to the GitHub README;
- `app.py`, a small launcher at the repository root (the `app_file` Spaces runs).
No data or weights are included; the app fetches them with `weather-lab bootstrap` at startup.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import yaml

from weather_lab.common import ROOT

SPACE_META = Path(__file__).with_name("space.yaml")
SPACE_INCLUDE = ("requirements.txt", "pyproject.toml", "src/", "configs/", "benchmarks/specs/", "docs/", "LICENSE")
LAUNCHER = '''"""Hugging Face Space entry point (generated by `weather-lab-app build-space`)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

from weather_lab_app.main import main  # noqa: E402

main()
'''


def git_intended_files(root: Path = ROOT) -> list[str]:
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=root,
                         capture_output=True, text=True, check=True).stdout.split()
    return sorted(f for f in out if (root / f).is_file())


def build_space(out: Path, log=print) -> Path:
    meta = yaml.safe_load(SPACE_META.read_text())
    if out.exists():
        shutil.rmtree(out)
    files = [f for f in git_intended_files() if f.startswith(SPACE_INCLUDE)]
    for f in files:
        (out / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, out / f)
    front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000).strip()
    (out / "README.md").write_text(f"---\n{front}\n---\n\n{(ROOT / 'README.md').read_text()}")
    (out / meta["app_file"]).write_text(LAUNCHER)
    log(f"Space content in {out}: {len(files) + 2} files, no data or weights (fetched by bootstrap at startup)")
    return out
